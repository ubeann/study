#!/usr/bin/env python3
"""Validate every note under notes/ and optionally rebuild notes/INDEX.md.

Usage:
    python3 scripts/check_notes.py               # validate, exit 1 on any failure
    python3 scripts/check_notes.py --write-index # validate and rebuild notes/INDEX.md

Rules (see README.md "Note anatomy"):
    required keys: title, kind, area, date, status, sources
    kind    in concept | comparison | article | lookup
    status  in draft | verified
    area    equals the note's parent directory name
    date    is YYYY-MM-DD
    sources is a non-empty list of http(s) URLs
    diagram, when present, points at an existing file
    a verified note has no unverified claims
"""
from __future__ import annotations

import datetime as _dt
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
NOTES = ROOT / "notes"
INDEX = NOTES / "INDEX.md"
KINDS = ("concept", "comparison", "article", "lookup")
STATUSES = ("draft", "verified")
REQUIRED = ("title", "kind", "area", "date", "status", "sources")

Frontmatter = dict[str, "str | list[str]"]


def parse_frontmatter(text: str) -> tuple[Frontmatter | None, str | None]:
    """Parse the small YAML subset the templates use: scalars, `key:` + `- item` lists, `[a, b]` lists."""
    if not text.startswith("---\n"):
        return None, "missing frontmatter block at top of file"
    end = text.find("\n---", 4)
    if end == -1:
        return None, "frontmatter block is not closed with ---"
    data: Frontmatter = {}
    key: str | None = None
    for raw in text[4:end].splitlines():
        line = raw.rstrip()
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        top = re.match(r"^([A-Za-z_][\w-]*):\s*(.*)$", line)
        if top and not line.startswith((" ", "\t")):
            key, value = top.group(1), top.group(2).strip()
            if value == "":
                data[key] = []
            elif value.startswith("[") and value.endswith("]"):
                data[key] = [v.strip().strip("\"'") for v in value[1:-1].split(",") if v.strip()]
            else:
                data[key] = value.strip("\"'")
            continue
        if line.lstrip().startswith("- ") and key is not None:
            bucket = data.get(key)
            if not isinstance(bucket, list):
                bucket = []
                data[key] = bucket
            bucket.append(line.lstrip()[2:].strip().strip("\"'"))
            continue
        return None, f"cannot parse frontmatter line: {line!r}"
    return data, None


def check_note(path: pathlib.Path) -> tuple[list[str], Frontmatter]:
    errors: list[str] = []
    fm, err = parse_frontmatter(path.read_text(encoding="utf-8"))
    if err or fm is None:
        return [err or "unreadable frontmatter"], {}
    for k in REQUIRED:
        if k not in fm or fm[k] in ("", []):
            errors.append(f"missing `{k}`")
    if fm.get("kind") not in KINDS:
        errors.append(f"`kind` must be one of {', '.join(KINDS)}")
    if fm.get("status") not in STATUSES:
        errors.append(f"`status` must be one of {', '.join(STATUSES)}")
    if fm.get("area") != path.parent.name:
        errors.append(f"`area` is {fm.get('area')!r} but the note sits in {path.parent.name!r}")
    try:
        _dt.date.fromisoformat(str(fm.get("date", "")))
    except ValueError:
        errors.append("`date` must be YYYY-MM-DD")
    sources = fm.get("sources") or []
    if isinstance(sources, str):
        sources = [sources]
    bad = [s for s in sources if not re.match(r"^https?://\S+$", s)]
    if bad:
        errors.append(f"`sources` entries must be http(s) URLs: {bad}")
    if fm.get("status") == "verified" and fm.get("unverified"):
        errors.append("a `verified` note still lists `unverified` claims")
    diagram = fm.get("diagram")
    if isinstance(diagram, str) and diagram and not (ROOT / diagram).exists():
        errors.append(f"`diagram` file not found: {diagram}")
    return errors, fm


def write_index(rows: list[tuple[pathlib.Path, Frontmatter]]) -> None:
    by_area: dict[str, list[tuple[pathlib.Path, Frontmatter]]] = {}
    for path, fm in rows:
        by_area.setdefault(path.parent.name, []).append((path, fm))
    out = ["# Notes index", "", "Generated by `python3 scripts/check_notes.py --write-index`. Do not edit by hand.", ""]
    for area in sorted(by_area):
        out += [f"## {area}", "", "| date | kind | status | note |", "|---|---|---|---|"]
        for path, fm in sorted(by_area[area], key=lambda r: (str(r[1].get("date")), r[0].name), reverse=True):
            rel = path.relative_to(NOTES).as_posix()
            out.append(f"| {fm.get('date')} | {fm.get('kind')} | {fm.get('status')} | [{fm.get('title')}]({rel}) |")
        out.append("")
    INDEX.write_text("\n".join(out).rstrip() + "\n", encoding="utf-8")


def main(argv: list[str]) -> int:
    notes = sorted(p for p in NOTES.rglob("*.md") if p.name != "INDEX.md")
    failures = 0
    rows: list[tuple[pathlib.Path, Frontmatter]] = []
    for path in notes:
        errors, fm = check_note(path)
        rel = path.relative_to(ROOT).as_posix()
        if errors:
            failures += 1
            print(f"FAIL {rel}")
            for e in errors:
                print(f"  - {e}")
        else:
            rows.append((path, fm))
    print(f"{len(notes) - failures}/{len(notes)} notes ok")
    if "--write-index" in argv:
        write_index(rows)
        print(f"wrote {INDEX.relative_to(ROOT).as_posix()}")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
